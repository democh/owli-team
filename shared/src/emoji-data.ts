/** 全部表情的扁平索引（搜索用；模块加载时构建一次） */
export const ALL_EMOJIS: EmojiItem[] = EMOJI_CATEGORIES.flatMap((c) => c.items)

const BY_CHAR = new Map(ALL_EMOJIS.map((i) => [i.char, i]))

/** 合法性校验（服务端 reactions 用）：字符必须在库内 或 是常见 ZWJ/修饰符序列（宽松放行 ≤4 码点） */
export function isKnownEmoji(char: string): boolean {
  return BY_CHAR.has(char)
}

/** 宽松 emoji 形态校验（库外但形态合法的 emoji 序列也允许，如肤色变体；≤6 码点防滥用） */
export function isEmojiLike(char: string): boolean {
  if (!char) return false
  const points = [...char]
  if (points.length > 6) return false
  if (isKnownEmoji(char)) return true
  // 每个码点须为：扩展 pictographic / ZWJ / VS16 / 键帽组合符 / 肤色修饰符 / 区域指示符（旗帜）
  const isEmojiCodePoint = (p: string): boolean => {
    const cp = p.codePointAt(0) ?? 0
    return (
      /\p{Extended_Pictographic}/u.test(p) ||
      cp === 0x200d || // ZWJ
      cp === 0xfe0f || // VS16
      cp === 0x20e3 || // 键帽组合符
      (cp >= 0x1f3fb && cp <= 0x1f3ff) || // 肤色修饰符
      (cp >= 0x1f1e6 && cp <= 0x1f1ff) || // 区域指示符（旗帜）
      /^[0-9#*]$/.test(p) // 键帽数字基符
    )
  }
  return points.every(isEmojiCodePoint) && points.some((p) => /\p{Extended_Pictographic}/u.test(p))
}

/** 客户端搜索：名称 / 关键词子串匹配（小写；≤50 条） */
export function searchEmoji(query: string, limit = 50): EmojiItem[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  const out: EmojiItem[] = []
  for (const item of ALL_EMOJIS) {
    if (item.name.includes(q) || item.keywords.toLowerCase().includes(q)) {
      out.push(item)
      if (out.length >= limit) break
    }
  }
  return out
}
