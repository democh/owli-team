/** bits → 卦名（表外兜底：上象 + 下象）；bits 非法 → '' */
export function guaNameOf(bits: string): string {
  if (HEX_NAMES[bits]) return HEX_NAMES[bits]!
  const lower = TRIGRAM[bits.slice(0, 3)]
  const upper = TRIGRAM[bits.slice(3)]
  if (!lower || !upper) return ''
  return `${upper.nature}${lower.nature}`
}
